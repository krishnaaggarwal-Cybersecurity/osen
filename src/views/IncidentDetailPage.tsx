import React, { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { useApp } from '../context/AppContext';
import { CommandMapComponent } from '../components/map/CommandMapComponent';
import { ArrowLeft, Download, Clock, MapPin, PhoneCall, Copy, Check, X, CheckCircle2 } from 'lucide-react';

export const IncidentDetailPage: React.FC = () => {
  const { id } = useParams<{ id: string }>();
  const navigate = useNavigate();
  const { incidents, maskedPhone, dismissIncident, acknowledgeIncident, dispatchIncident } = useApp();
  const [copied, setCopied] = useState<boolean>(false);
  const [isGeneratingPdf, setIsGeneratingPdf] = useState<boolean>(false);

  const incident = incidents.find((i) => i.id === id) || incidents[0];
  const isPending = incident?.status === 'AWAITING' || incident?.status === 'DETECTED';
  const canRequestDispatch = isPending || incident?.status === 'AUTO-ESCALATED';

  // Requirement A.12: Page window title formula
  useEffect(() => {
    if (incident) {
      document.title = `Incident ${incident.id} | NetraGridAI`;
    }
  }, [incident]);

  const handleCopyGps = () => {
    const text = `${incident.coordinates.lat.toFixed(4)}, ${incident.coordinates.lng.toFixed(4)}`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadPdf = () => {
    setIsGeneratingPdf(true);
    setTimeout(() => {
      setIsGeneratingPdf(false);
      const pdfContent = `
===================================================================
NETRAGRID AI — SMART CITY EMERGENCY DISPATCH INCIDENT BRIEF
===================================================================
Incident ID: ${incident.id}
Date & Time: ${incident.detectedAt}
Severity: ${incident.severity}
Status: ${incident.status}

LOCATION & SENSOR DATA
-------------------------------------------------------------------
Camera ID: ${incident.cameraId} (${incident.cameraName})
Location: ${incident.location}
GPS Coordinates: ${incident.coordinates.lat} N, ${incident.coordinates.lng} E
Vehicle Type: ${incident.vehicleType}
Impact Metrics: ${incident.impactSpeed}
AI Confidence: ${(incident.confidence * 100).toFixed(1)}% (YOLOv8 PyTorch)

TELEPHONY & DISPATCH SUMMARY
-------------------------------------------------------------------
Configured Responder Target: ${maskedPhone}
Call Status: ${incident.dispatchDetails?.callStatus || 'NOT CONNECTED'}
Language Protocol: ${incident.dispatchDetails?.language || 'Not configured'}
Call SID: ${incident.dispatchDetails?.callSid || 'No call placed'}
Duration: ${incident.dispatchDetails?.callDuration ? `${incident.dispatchDetails.callDuration} seconds` : 'Not available'}
Note: Dispatch actions are recorded in Supabase; no emergency call is placed by this app.

TIMELINE LOG
-------------------------------------------------------------------
${incident.timeline.map((t) => `[${t.time}] ${t.title}: ${t.description}`).join('\n')}

===================================================================
Generated by NetraGridAI Emergency Command System
===================================================================
      `;
      const blob = new Blob([pdfContent], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `NetraGridAI_Brief_${incident.id}.txt`;
      a.click();
      URL.revokeObjectURL(url);
    }, 1200);
  };

  if (!incident) {
    return (
      <div className="p-8 max-w-3xl mx-auto">
        <div className="bg-white border border-slate-200 rounded-xl p-6">
          <h1 className="font-bold text-slate-900">Incident unavailable</h1>
          <p className="text-sm text-slate-500 mt-2">This incident could not be loaded from the persisted incident ledger.</p>
          <button onClick={() => navigate('/incidents')} className="mt-4 text-sm font-semibold text-[#0B7FF5] hover:underline">
            Return to incidents
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="p-6 md:p-8 space-y-6 max-w-[1400px] mx-auto font-sans">
      {/* Header Bar */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 bg-white p-5 rounded-xl border border-slate-200 shadow-xs">
        <div className="flex items-center space-x-3">
          <button
            onClick={() => navigate('/incidents')}
            className="p-2.5 rounded-lg bg-slate-100 border border-slate-200 text-slate-700 hover:bg-slate-200 transition-calm"
          >
            <ArrowLeft className="w-4 h-4" />
          </button>
          <div>
            <div className="flex items-center space-x-2 font-mono">
              <h1 className="text-xl font-bold text-slate-900">{incident.id}</h1>
              <span className="bg-red-100 text-red-700 border border-red-200 text-xs px-2.5 py-0.5 rounded font-bold">
                {incident.severity}
              </span>
              <span
                className={`text-xs px-2.5 py-0.5 rounded font-bold border ${
                  incident.status === 'DISPATCHED' || incident.status === 'AUTO-ESCALATED'
                    ? 'bg-emerald-50 text-emerald-700 border-emerald-300'
                    : incident.status === 'ACKNOWLEDGED'
                    ? 'bg-indigo-50 text-indigo-700 border-indigo-300'
                    : 'bg-blue-50 text-[#0B7FF5] border-blue-200'
                }`}
              >
                {incident.status}
              </span>
            </div>
            <p className="text-xs text-slate-500 mt-0.5">{incident.cameraName}</p>
          </div>
        </div>

        {/* Primary Action Button */}
        <button
          onClick={handleDownloadPdf}
          disabled={isGeneratingPdf}
          className="px-5 py-2.5 rounded-full bg-[#0B7FF5] text-white font-bold text-xs tracking-wider uppercase hover:bg-blue-600 active:scale-[0.99] transition-calm flex items-center space-x-2 shadow-md shadow-blue-500/20"
        >
          {isGeneratingPdf ? (
            <>
              <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
              <span>Generating summary...</span>
            </>
          ) : (
            <>
              <Download className="w-4 h-4" />
              <span>DOWNLOAD INCIDENT SUMMARY</span>
            </>
          )}
        </button>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        <div className="lg:col-span-7 space-y-6">
          <div className="bg-white border border-slate-200 rounded-xl p-5 space-y-4 shadow-xs">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3 font-mono">
              <span className="font-bold text-xs text-slate-900">YOLOv8 Frame Snapshot</span>
              <span className="text-xs text-[#0B7FF5] font-bold">Confidence: {(incident.confidence * 100).toFixed(1)}%</span>
            </div>

            <div className="relative aspect-video rounded-lg overflow-hidden border border-slate-200 bg-slate-900">
              <img src={incident.snapshotUrl} alt="Evidence" className="w-full h-full object-cover" />
              {incident.boundingBoxes.map((box, idx) => (
                <div
                  key={idx}
                  className="absolute border-2 border-[#0B7FF5] bg-[#0B7FF5]/20 rounded text-[10px] text-white font-mono font-bold px-1"
                  style={{
                    left: `${(box.x / 640) * 100}%`,
                    top: `${(box.y / 360) * 100}%`,
                    width: `${(box.width / 640) * 100}%`,
                    height: `${(box.height / 360) * 100}%`,
                  }}
                >
                  {box.label} {(box.confidence * 100).toFixed(0)}%
                </div>
              ))}
            </div>

            {/* Requirement B.3: The 3 Required Action Buttons */}
            <div className="grid grid-cols-3 gap-2 pt-2 border-t border-slate-100 font-mono text-xs">
              <button
                onClick={() => dismissIncident(incident.id)}
                disabled={!isPending}
                className="py-2 px-3 rounded-lg font-bold bg-slate-100 hover:bg-slate-200 text-slate-700 border border-slate-200 transition-calm flex items-center justify-center space-x-1.5"
              >
                <X className="w-4 h-4" />
                <span>Dismiss</span>
              </button>

              <button
                onClick={() => acknowledgeIncident(incident.id)}
                disabled={!isPending}
                className="py-2 px-3 rounded-lg font-bold bg-indigo-50 hover:bg-indigo-100 text-indigo-700 border border-indigo-300 transition-calm flex items-center justify-center space-x-1.5"
              >
                <CheckCircle2 className="w-4 h-4" />
                <span>Acknowledge</span>
              </button>

              <button
                onClick={() => dispatchIncident(incident.id)}
                disabled={!canRequestDispatch}
                className="py-2 px-3 rounded-lg font-bold bg-emerald-600 hover:bg-emerald-700 text-white transition-calm flex items-center justify-center space-x-1.5 shadow-xs"
              >
                <PhoneCall className="w-4 h-4" />
                <span>Request Dispatch</span>
              </button>
            </div>
          </div>

          <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4 shadow-xs">
            <div className="flex items-center space-x-2 border-b border-slate-100 pb-4">
              <PhoneCall className="w-4 h-4 text-[#0B7FF5]" />
              <h2 className="font-bold text-sm text-slate-900">Dispatch Action Record</h2>
            </div>

            <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs font-mono">
              <div className="p-3 bg-slate-50 rounded-lg border border-slate-200">
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Recipient</span>
                <span className="text-slate-900 font-bold">{maskedPhone}</span>
              </div>

              <div className="p-3 bg-slate-50 rounded-lg border border-slate-200">
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Protocol</span>
                <span className="text-[#0B7FF5] font-bold">Provider not connected</span>
              </div>

              <div className="p-3 bg-slate-50 rounded-lg border border-slate-200">
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Call SID</span>
                <span className="text-slate-900 truncate block font-bold">
                  {incident.dispatchDetails?.callSid || 'No call placed'}
                </span>
              </div>

              <div className="p-3 bg-slate-50 rounded-lg border border-slate-200">
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Status</span>
                <span className="text-[#0B7FF5] font-bold uppercase">
                  {incident.dispatchDetails?.callStatus || 'not connected'}
                </span>
              </div>
            </div>
            <p className="text-[11px] text-amber-700">
              Operator dispatch actions are recorded in Supabase. No outbound emergency call is placed by this app.
            </p>
          </div>
        </div>

        <div className="lg:col-span-5 space-y-6">
          <div className="bg-white border border-slate-200 rounded-xl p-5 space-y-4 shadow-xs">
            <div className="flex items-center justify-between">
              <div className="flex items-center space-x-2">
                <MapPin className="w-4 h-4 text-[#0B7FF5]" />
                <span className="font-bold text-xs text-slate-900">{incident.location}</span>
              </div>
              <button
                onClick={handleCopyGps}
                className="px-2.5 py-1 bg-slate-100 border border-slate-200 rounded-lg text-[10px] font-mono text-[#0B7FF5] hover:bg-slate-200 flex items-center space-x-1 font-bold"
              >
                {copied ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                <span>{copied ? 'Copied' : 'Copy GPS'}</span>
              </button>
            </div>

            <CommandMapComponent incidents={[incident]} height="220px" />
          </div>

          <div className="bg-white border border-slate-200 rounded-xl p-6 space-y-4 shadow-xs">
            <div className="flex items-center space-x-2 border-b border-slate-100 pb-4">
              <Clock className="w-4 h-4 text-[#0B7FF5]" />
              <h2 className="font-bold text-sm text-slate-900">Event Audit Timeline</h2>
            </div>

            <div className="space-y-4 relative pl-4 border-l border-slate-200 ml-2 text-xs">
              {incident.timeline.map((event, idx) => (
                <div key={idx} className="relative space-y-1">
                  <div className="absolute -left-[21px] top-1 w-2.5 h-2.5 rounded-full bg-[#0B7FF5]" />
                  <div className="flex items-center justify-between">
                    <span className="font-bold text-slate-900">{event.title}</span>
                    <span className="font-mono text-[10px] text-slate-400">{event.time}</span>
                  </div>
                  <p className="text-slate-500 text-[11px] leading-relaxed">{event.description}</p>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
